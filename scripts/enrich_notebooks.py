"""교육용 설명 셀을 실습 노트북에 일관되게 추가한다.

노트북의 기존 코드와 출력은 유지하고 Markdown 셀만 삽입한다. 이미 보강된
노트북은 마커를 확인해 건너뛰므로 여러 번 실행해도 셀이 중복되지 않는다.
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
MARKER = "<!-- onsite-practice -->"


def markdown(text: str) -> dict:
    body = f"{MARKER}\n{text.strip()}\n"
    return {
        "cell_type": "markdown",
        "id": f"onsite-{hashlib.sha1(body.encode('utf-8')).hexdigest()[:8]}",
        "metadata": {},
        "source": body.splitlines(keepends=True),
    }


def enrich(filename: str, before: dict[int, list[str]], after: dict[int, list[str]], replacements=None) -> None:
    path = ROOT / filename
    notebook = json.loads(path.read_text(encoding="utf-8"))
    if any(MARKER in "".join(cell.get("source", [])) for cell in notebook["cells"]):
        changed = False
        if notebook.get("nbformat_minor", 0) >= 5:
            for cell in notebook["cells"]:
                source = "".join(cell.get("source", []))
                if MARKER in source and "id" not in cell:
                    cell["id"] = f"onsite-{hashlib.sha1(source.encode('utf-8')).hexdigest()[:8]}"
                    changed = True
        if changed:
            path.write_text(json.dumps(notebook, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
        print(f"skip: {filename}")
        return

    replacements = replacements or {}
    cells = []
    for index, original in enumerate(notebook["cells"]):
        cells.extend(markdown(text) for text in before.get(index, []))
        cells.append(replacements.get(index, original))
        cells.extend(markdown(text) for text in after.get(index, []))
    if notebook.get("nbformat_minor", 0) < 5:
        for cell in cells:
            cell.pop("id", None)
    notebook["cells"] = cells
    path.write_text(json.dumps(notebook, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    print(f"updated: {filename} ({len(cells)} cells)")


